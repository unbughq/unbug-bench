FIXTURE = ROOT / 'tests/factory/fixtures/invalid-runs-public-cards.json.gz'


def cards():
    assert hashlib.sha256(FIXTURE.read_bytes()).hexdigest() == 'beaf4962da5544da4e7b8b95fc14903d348e4a9e781c2f3103f4e98ca7a334c4'
    rows = json.loads(gzip.decompress(FIXTURE.read_bytes()))
    return rows


class AccountingTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(); self.addCleanup(self.temporary.cleanup)
        self.work = Path(self.temporary.name)
        self.path = self.work / 'ledger.json'
        self.card = cards()[0]['card']
        self.original = copy.deepcopy(self.card['continuation_budget'])
        self.path.write_text(json.dumps(self.original))
        (self.work / 'usage-receipts').mkdir()

    def ledger(self): return json.loads(self.path.read_text())

    def reserve(self, maximum=10, operation=None, name='builder-continuation', lease_id=None):
        lease = Lease(lease_id or str(uuid.uuid4()), 'claude/claude-opus-5-5', 'claude-account1', 1,
                      'subscription', 'anthropic', 'claude-account1')
        row = budget.reserve_invocation(self.path, lease, maximum, 1000,
            operation_id=operation or str(uuid.uuid4()), call_name=name)
        return lease, row

    def receipt(self, lease, values, *, final=False):
        events = [{'id': identity, 'cost': amount, 'role': 'writer', 'invocation': 'builder-continuation'}
                  for identity, amount in values]
        relative = 'usage-receipts/' + lease.lease_id + '.json'
        value = {'lease_id': lease.lease_id, 'invocation': 'builder-continuation',
                 'events': events, 'booked_event_ids': [e['id'] for e in events],
                 'usage_delta': {'cost': sum(v for _, v in values)}, 'final_usage_known': final}
        (self.work / relative).write_text(json.dumps(value))
        return relative

    def wait(self, lease=None, call=None):
        record = {'wait_id': str(uuid.uuid4()), 'lease_id': lease.lease_id if lease else None,
                  'call_id': call, 'route': 'another/next-candidate', 'account': 'account3', 'settled': False}
        (self.work / 'provider_wait.json').write_text(json.dumps(record))
        return record

    def test_real_inventory_preserves_known_spend_and_legacy_waste(self):
        rows = cards()
        self.assertEqual(len(rows), 58)
        for row in rows:
            ledger = row['card'].get('continuation_budget')
            if ledger is None: continue
            summary = budget.case_spending(ledger, row['card'].get('models_used'))
            if summary['spent_usd'] is not None:
                self.assertAlmostEqual(summary['total_spent_usd'], summary['spent_usd'] + summary['infrastructure_waste_usd'], places=8)
        legacy = budget.case_spending(rows[1]['card']['continuation_budget'])
        self.assertEqual(legacy['infrastructure_waste_usd'], 16)

    def test_unknown_gap_replay_and_late_receipt_on_real_ledger(self):
        baseline = budget.case_spending(self.original)['total_spent_usd']
        lease, _ = self.reserve()
        call = self.receipt(lease, [('part-a', 3), ('part-b', 2)])
        record = self.wait(lease, call)
        self.assertEqual(budget.settle(record, work=self.work, ledger_path=self.path), 10)
        self.assertTrue(record['settled'])
        self.assertEqual(budget.settle(record, work=self.work, ledger_path=self.path), 0)
        self.assertAlmostEqual(budget.case_spending(self.ledger())['total_spent_usd'], baseline + 10)
        self.receipt(lease, [('part-a', 3), ('part-b', 2), ('final', 3)], final=True)
        self.assertEqual(budget.settle(record, work=self.work, ledger_path=self.path), -2)
        self.assertEqual(budget.settle(record, work=self.work, ledger_path=self.path), 0)
        self.assertAlmostEqual(budget.case_spending(self.ledger())['total_spent_usd'], baseline + 8)

    def test_aggregate_fallback_dedup_ignores_candidate_route(self):
        l1, _ = self.reserve(6); l2, _ = self.reserve(4)
        p1 = self.receipt(l1, [('one', 3)]); p2 = self.receipt(l2, [('two', 2)])
        # Already streamed costs are never added again by settlement.
        with budget.ledger_transaction(self.path) as ledger:
            for relative in (p1, p2):
                event = json.loads((self.work / relative).read_text())['events'][0]
                ledger['events'].append(event); ledger['cost'] += event['cost']
        aggregate = 'usage-receipts/aggregate.json'
        (self.work / aggregate).write_text(json.dumps({'receipts': [p1, p2, p1], 'usage_delta': {'cost': 500}}))
        record = self.wait(l2, aggregate)
        self.assertEqual(budget.settle(record, work=self.work, ledger_path=self.path), 5)
        self.assertEqual(budget.settle(record, work=self.work, ledger_path=self.path), 0)
        self.assertEqual(len(self.ledger()['events']), len(self.original['events']) + 2)

    def test_null_denial_is_zero_and_path_escape_refuses_without_writes(self):
        record = self.wait()
        self.assertEqual(budget.settle(record, work=self.work, ledger_path=self.path), 0)
        before = self.path.read_bytes()
        for path in ('../escape.json', '/tmp/escape.json', 'usage-receipts/../../escape.json'):
            with self.assertRaisesRegex(budget.BudgetError, 'invalid_usage_receipt'):
                budget.settle({**record, 'call_id': path}, work=self.work, ledger_path=self.path)
        self.assertEqual(self.path.read_bytes(), before)

    def test_duplicate_reservation_and_parallel_admission(self):
        lease, row = self.reserve()
        again = budget.reserve_invocation(self.path, lease, 10, 1000,
            operation_id=row['operation_id'], call_name=row['call_name'])
        self.assertEqual(row, again)
        baseline = budget.case_spending(self.original)['total_spent_usd']
        def admit(_):
            candidate = Lease(str(uuid.uuid4()), lease.route, lease.account, 1, lease.billing, lease.family, lease.pool)
            try:
                budget.reserve_invocation(self.path, candidate, 6, baseline + 20,
                    operation_id=str(uuid.uuid4()), call_name='reviewer-concurrent')
                return True
            except budget.BudgetError: return False
        with ThreadPoolExecutor(2) as pool:
            self.assertEqual(sum(pool.map(admit, range(2))), 1)
        self.assertEqual(budget.outstanding_reservations(self.ledger()), Decimal(16))

    def test_factory_bug_moves_real_event_without_refunding_batch(self):
        # One genuine billed writer event, classified only after its operation
        # and reviewed-fix attribution have been retained.
        ledger = self.ledger()
        event = next(e for e in ledger['events'] if e.get('list_cost_usd', 0) > 0)
        operation = str(uuid.uuid4()); lease, _ = self.reserve(20, operation)
        with budget.ledger_transaction(self.path) as ledger:
            ledger['invocation_reservations'][lease.lease_id].update(state='settled', event_ids=[event['id']])
            ledger['infrastructure_waste'] = [{'schema_version': 1, 'kind': 'factory_bug',
                'id': str(uuid.uuid4()), 'diagnosis_sha256': 'd' * 64, 'fix_commit': 'f' * 40,
                'fix_attribution_sha256': 'a' * 64, 'operation_ids': [operation], 'event_ids': [event['id']],
                'infrastructure_waste_usd': float(budget.event_charge(event))}]
        summary = budget.case_spending(self.ledger())
        original = budget.case_spending(self.original)
        self.assertAlmostEqual(summary['total_spent_usd'], original['total_spent_usd'], places=8)
        self.assertAlmostEqual(summary['spent_usd'] + summary['infrastructure_waste_usd'], original['spent_usd'], places=8)
        self.assertGreater(summary['infrastructure_waste_usd'], 0)


class JobMoneyTests(unittest.TestCase):
    def test_missing_and_stale_authority_fail_closed(self):
        channel = {'schema': 1, 'batch': 'practice', 'job': 'original', 'case': cards()[0]['card']['case'],
            'reservation_id': str(uuid.uuid4()), 'revision': 2, 'source_generation': 'e' * 64,
            'committed_total_usd': '80.000000000', 'batch_deadline': '2026-11-01T00:00:00Z'}
        self.assertEqual(job_authority.read(channel, channel, now=0).committed_total_usd, Decimal(80))
        for candidate in (None, {}, {**channel, 'revision': 1}, {**channel, 'source_generation': 'f' * 64},
                          {**channel, 'committed_total_usd': 'NaN'}, {**channel, 'committed_total_usd': '80.0'}):
            with self.assertRaisesRegex(budget.BudgetError, 'money_wait'):
                job_authority.read(candidate, channel, now=0)
        with self.assertRaisesRegex(budget.BudgetError, 'retired_batch_bound'):
            job_authority.read(channel, channel, now=1e12)
        with self.assertRaisesRegex(budget.BudgetError, 'money_wait'):
            job_authority.for_case(SimpleNamespace(case_id=channel['case'], card={}))


